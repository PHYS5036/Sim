"""Read Geant4 VRML2FILE output and display geometry and tracks with Plotly.

This is intentionally a reader for Geant4's flat IndexedFaceSet/IndexedLineSet
output, not a general VRML reader. Coordinates are in Geant4's default mm.
"""

import json
import math
import re
from pathlib import Path


PARTICLE_COLOURS = {
    (0, 1, 0): "gamma",
    (1, 0, 0): "e-",
    (0, 1, 1): "e+",
    (1, 0, 1): "proton",
    (1, 1, 0): "ion / alpha",
    (0, 0, 1): "neutron",
}


def _numbers(text, integer=False):
    values = [int(x) if integer else float(x)
              for x in text.replace(",", " ").split()]
    if not all(math.isfinite(x) for x in values):
        raise ValueError("Non-finite VRML coordinate or colour")
    return values


def _groups(indices, count, minimum):
    groups, current = [], []
    for index in indices:
        if index == -1:
            if len(current) < minimum:
                raise ValueError("Too few vertices in VRML primitive")
            groups.append(current)
            current = []
        elif 0 <= index < count:
            current.append(index)
        else:
            raise ValueError(f"VRML vertex index {index} outside [0, {count})")
    if current:
        raise ValueError("VRML coordIndex must end with -1")
    if not groups:
        raise ValueError("Empty VRML coordIndex")
    return groups


def read_vrml(path):
    """Return a JSON-serializable scene, preserving volume names and polylines."""
    text = Path(path).read_text()
    if not text.startswith("#VRML V2.0") or "Generated by VRML 2.0 driver of GEANT4" not in text:
        raise ValueError("Expected Geant4 VRML2FILE output")
    if re.search(r"\b(Transform|USE|DEF|PointSet|Sphere)\b", re.sub(r"#[^\n]*", "", text)):
        raise ValueError("Unsupported VRML node; use geometry and trajectories without markers")
    scene = {"schema": "geant4-scene-v1", "units": "mm", "geometry": [], "tracks": []}
    blocks = re.split(r"#---------- ", text)[1:]
    shape_count = 0
    for block in blocks:
        if block.startswith("CAMERA"):
            continue
        kind = re.search(r"geometry\s+(IndexedFaceSet|IndexedLineSet)\s*\{", block)
        coords = re.search(r"\bpoint\s*\[([^]]*)\]", block, re.S)
        indices = re.search(r"\bcoordIndex\s*\[([^]]*)\]", block, re.S)
        colour = re.search(r"diffuseColor\s+([^\n}]+)", block)
        if not all((kind, coords, indices, colour)) or block.count("Shape {") != 1:
            raise ValueError("Unsupported or incomplete Geant4 VRML shape")
        values = _numbers(coords.group(1))
        rgb = _numbers(colour.group(1))
        if not values or len(values) % 3 or len(rgb) != 3 or not all(0 <= x <= 1 for x in rgb):
            raise ValueError("Invalid VRML vertices or RGB colour")
        vertices = [values[i:i + 3] for i in range(0, len(values), 3)]
        is_mesh = kind.group(1) == "IndexedFaceSet"
        groups = _groups(_numbers(indices.group(1), integer=True), len(vertices),
                         3 if is_mesh else 2)
        if is_mesh:
            # Geant4 polyhedra emit convex triangle/quad facets.
            triangles = [[face[0], face[i], face[i + 1]]
                         for face in groups for i in range(1, len(face) - 1)]
            name = block.splitlines()[0].removeprefix("SOLID: ").strip()
            scene["geometry"].append({"name": name, "vertices": vertices,
                                      "triangles": triangles, "colour": rgb})
        else:
            for line in groups:
                scene["tracks"].append({"points": [vertices[i] for i in line],
                                        "colour": rgb})
        shape_count += 1
    if shape_count != text.count("Shape {") or not scene["geometry"]:
        raise ValueError("No geometry or unparsed shapes in VRML export")
    return scene


def load_scene(path):
    """Load a scene.json created by visualize.py."""
    scene = json.loads(Path(path).read_text())
    if scene.get("schema") != "geant4-scene-v1" or scene.get("units") != "mm":
        raise ValueError("Unsupported scene JSON schema or units")
    return scene


def figure(scene, geometry_opacity=0.25):
    """Create a rotatable notebook figure; click legend entries to hide volumes."""
    import plotly.graph_objects as go

    if not 0 <= geometry_opacity <= 1:
        raise ValueError("geometry_opacity must be between 0 and 1")

    def css(rgb):
        return "rgb(%d,%d,%d)" % tuple(round(x * 255) for x in rgb)

    fig = go.Figure()
    for mesh in scene["geometry"]:
        x, y, z = zip(*mesh["vertices"])
        i, j, k = zip(*mesh["triangles"])
        fig.add_trace(go.Mesh3d(
            x=x, y=y, z=z, i=i, j=j, k=k, name=mesh["name"],
            color=css(mesh["colour"]), opacity=geometry_opacity,
            showlegend=True, flatshading=True))
    # One trace per colour keeps large scenes responsive without losing tracks.
    lines = {}
    for track in scene["tracks"]:
        key = tuple(track["colour"])
        coordinates = lines.setdefault(key, [[], [], []])
        for axis in range(3):
            coordinates[axis].extend(p[axis] for p in track["points"])
            coordinates[axis].append(None)
    for rgb, (x, y, z) in lines.items():
        name = PARTICLE_COLOURS.get(rgb, "track " + css(rgb))
        fig.add_trace(go.Scatter3d(x=x, y=y, z=z, mode="lines", name=name,
                                  line={"color": css(rgb), "width": 3}))
    fig.update_layout(
        title="Geant4 geometry and trajectories",
        scene={"aspectmode": "data", "xaxis_title": "x (mm)",
               "yaxis_title": "y (mm)", "zaxis_title": "z (mm)"},
        margin={"l": 0, "r": 0, "t": 40, "b": 0}, height=700)
    return fig
